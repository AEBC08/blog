function toKebabCase(name: string): string {
  return name
    .replace(/^Icon/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()
}

/** Tabler icons addressable as `name="arrow-right"` (or `tabler:arrow-right`). */
export const TABLER_ICONS: Record<string, Component> = Object.fromEntries(
  Object.entries(TABLER_COMPONENTS).map(([name, component]) => [
    toKebabCase(name),
    component,
  ]),
)

